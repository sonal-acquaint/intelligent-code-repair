<?php

declare(strict_types=1);

namespace Acquaint\AiBugFixer\Commands;

use Acquaint\AiBugFixer\Contracts\AiFixClient;
use Illuminate\Console\Command;
use Throwable;

class TestConnectionCommand extends Command
{
    /**
     * The name and signature of the console command.
     */
    protected $signature = 'ai-bug-fixer:test';

    /**
     * The console command description.
     */
    protected $description = 'Test connection to the Python AI service';

    /**
     * Execute the console command.
     */
    public function handle(AiFixClient $client): int
    {
        $pythonUrl = config('ai-bug-fixer.python_url');
        $this->info("Testing connection to AI Bug Fixer Python service at: {$pythonUrl}");

        $dummyPayload = [
            'id' => 'test-connection-probe',
            'timestamp' => now()->toIso8601String(),
            'exception_class' => 'Exception',
            'message' => 'Test connection probe generated by artisan ai-bug-fixer:test',
            'code' => 0,
            'file' => __FILE__,
            'relative_file' => 'src/Commands/TestConnectionCommand.php',
            'line' => __LINE__,
            'code_snippet' => [
                __LINE__ => '$this->info("Testing connection...");',
            ],
            'trace' => [],
            'environment' => app()->environment(),
            'laravel_version' => app()->version(),
            'php_version' => PHP_VERSION,
        ];

        $startTime = microtime(true);

        try {
            $this->output->write('Sending probe request to /analyze endpoint... ');
            $response = $client->analyze($dummyPayload);
            $elapsed = round((microtime(true) - $startTime) * 1000, 2);

            $this->output->writeln('<info>SUCCESS</info>');
            $this->line("Response time: {$elapsed}ms");
            $this->line('Service status: ' . ($response['status'] ?? 'unknown'));

            if (! empty($response['summary'])) {
                $this->line("Summary: {$response['summary']}");
            }

            return self::SUCCESS;
        } catch (Throwable $e) {
            $this->output->writeln('<error>FAILED</error>');
            $this->error('Connection failed: ' . $e->getMessage());
            $this->line('Please check that the Python service is running and accessible at: ' . $pythonUrl);

            return self::FAILURE;
        }
    }
}
